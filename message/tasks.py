import logging

from celery import current_app, shared_task

from message.services.ai_reply_service import AIReplyService

logger = logging.getLogger(__name__)


def revoke_task(task_id):
    """Best-effort revoke of a scheduled task. Never raises."""
    if not task_id:
        return
    try:
        current_app.control.revoke(task_id)
    except Exception:
        logger.exception("Failed to revoke AI reply task %s", task_id)


@shared_task(name="message.send_ai_reply")
def send_ai_reply(conversation_id, task_id=None):
    """Delayed AI reply for a conversation.

    The ``task_id`` is generated by ``AIReplyService.maybe_schedule_reply`` and
    stored on the conversation. It is passed back here so that only the most
    recently scheduled task for a conversation can ever send a reply: a task
    superseded by a newer inbound message, or cancelled by a human takeover, is
    ignored because its id no longer matches the conversation.
    """
    AIReplyService._generate_and_send(conversation_id, task_id=task_id)
